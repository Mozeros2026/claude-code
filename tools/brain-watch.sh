#!/usr/bin/env bash
# Brain-builder watcher — THE KEYSTONE, shipped as a detector, not a daemon.
# Answers "which nodes have MATERIALS waiting but no fresh Brain?" — the gap the
# coverage audit misses (it checks Brain *presence*, this checks Brain *readiness
# vs materials*). It SURFACES + QUEUES; it NEVER builds. The Brain build stays
# MANUAL, DELIBERATE, Opus-only, human-invoked (momega-os.md §137 "not a daemon";
# CLAUDE.md non-negotiable #4). There is deliberately no code path from here to a
# build — that is the safety property, not an omission.
#
# Two material sources (cheap + git-durable; no Drive MCP, no LLM at runtime):
#   1. local   entities/<type>/<id>/materials/  (non-README files)
#   2. manifest registry/vault-manifest.md       (entity listed as having vault material)
# Freshness is read from the materials README **Status column** (✅/ingested),
# NOT file mtimes — this repo is cloned fresh per session, so mtimes are worthless.
# Live Drive-aware detection + mtime/content-hash staleness are BACKLOG (see BACKLOG.md).
#
# Usage: tools/brain-watch.sh [--gaps-only] [--write]
#   --gaps-only  one-line summary (for the SessionStart hook)
#   --write      regenerate registry/brain-queue.md
set -uo pipefail
cd "$(dirname "$0")/.."

GAPS_ONLY=0; WRITE=0
for a in "$@"; do [ "$a" = "--gaps-only" ] && GAPS_ONLY=1; [ "$a" = "--write" ] && WRITE=1; done

MANIFEST="registry/vault-manifest.md"

# A node is "vault-listed" if its id appears in the vault manifest (best-effort,
# word-boundary match). Cheap proxy for "the vault holds material for this node."
vault_listed(){ [ -f "$MANIFEST" ] && grep -qiE "\b${1//-/[ -]}\b" "$MANIFEST"; }

# Count materials README rows that name a file (backtick-quoted, real extension)
# but are NOT marked ingested (✅). That = a material listed-but-not-folded-in.
# Content-based, so it survives a fresh clone where mtimes are meaningless.
pending_materials(){
  local rm="$1/materials/README.md"
  [ -f "$rm" ] || { echo 0; return; }
  grep -cE '^\|.*`[^`]+\.(pdf|docx|pptx|key|csv|xlsx|md|txt|json|mp4)`' "$rm" \
    | { read total; grep -cE '^\|.*`[^`]+\.(pdf|docx|pptx|key|csv|xlsx|md|txt|json|mp4)`.*(✅|ingested)' "$rm" \
    | { read done; echo $(( total - done )); }; }
}

ready=""; pending=""; current=0; cold=0; nready=0; npending=0; total=0
for d in entities/*/*/; do
  [ -d "$d" ] || continue
  id=$(basename "$d"); type=$(basename "$(dirname "$d")"); total=$((total+1))
  # Archived/dormant nodes are never nagged.
  archived=0
  [ -f "${d}brain.md" ] && grep -qiE '^\*\*Status:\*\* *(ARCHIVED|DORMANT|INACTIVE)|^status: *(archived|dormant|inactive)' "${d}brain.md" && archived=1
  [ "$archived" = "1" ] && continue

  has_brain=0; [ -f "${d}brain.md" ] && has_brain=1
  matfiles=0
  [ -d "${d}materials" ] && matfiles=$(find "${d}materials" -type f ! -name 'README.md' 2>/dev/null | wc -l | tr -d ' ')
  vault=0; vault_listed "$id" && vault=1
  pend=$(pending_materials "$d"); [ -z "$pend" ] && pend=0

  if [ "$has_brain" = "0" ] && { [ "$matfiles" -gt 0 ] || [ "$vault" = "1" ]; }; then
    src="local"; [ "$matfiles" = "0" ] && src="vault-manifest"
    nready=$((nready+1))
    ready="${ready}| 🟢 **${type}/${id}** | ${matfiles} local + ${src} | no brain.md | \`/momega-onboard ${id} ${type}\` |\n"
  elif [ "$has_brain" = "1" ] && [ "$pend" -gt 0 ]; then
    npending=$((npending+1))
    pending="${pending}| 🟡 **${type}/${id}** | ${pend} material(s) not ✅ in README | brain exists, stale-vs-materials | \`/momega-brain update ${id}\` |\n"
  elif [ "$has_brain" = "1" ]; then
    current=$((current+1))
  else
    cold=$((cold+1))
  fi
done

summary="brain-watch: ${nready} ready-to-build, ${npending} new-materials-pending, ${current} current, ${cold} cold (${total} nodes)."

if [ "$GAPS_ONLY" = "1" ]; then
  echo "$summary"
  [ "$nready" -gt 0 ] && printf "%b" "$ready" | sed 's/^| 🟢 /  🟢 build-ready: /; s/ |.*$//'
  [ "$npending" -gt 0 ] && printf "%b" "$pending" | sed 's/^| 🟡 /  🟡 new-materials: /; s/ |.*$//'
  [ "$nready" = "0" ] && [ "$npending" = "0" ] && echo "  no node is waiting on a Brain build; the front door (/momega-onboard) is keeping up."
fi

out=""
out="${out}# Brain Build Queue — the keystone watcher's output\n\n"
out="${out}> Generated by \`tools/brain-watch.sh --write\`. The watcher **surfaces + queues**;\n"
out="${out}> it never builds. The Brain build is **manual, deliberate, Opus-only, human-invoked**\n"
out="${out}> (a human runs \`/momega-onboard\` or \`/momega-brain build\`). This file is the durable,\n"
out="${out}> cross-session list of nodes whose materials are waiting — the analogue of\n"
out="${out}> \`persona-sync-queue.md\` for Brains. Empty queue = the front door is keeping up.\n\n"
out="${out}${summary//brain-watch: /**}**\n\n"
out="${out}## 🟢 Ready to build (materials present, no Brain) — run \`/momega-onboard\`\n\n"
if [ "$nready" -gt 0 ]; then
  out="${out}| Node | Materials | Brain | Build command (human, Opus) |\n|------|-----------|-------|------------------------------|\n${ready}\n"
else
  out="${out}None — every node with materials already has a Brain.\n\n"
fi
out="${out}## 🟡 New materials pending (Brain exists, material not yet ingested) — run \`/momega-brain update\`\n\n"
if [ "$npending" -gt 0 ]; then
  out="${out}| Node | Pending | State | Update command |\n|------|---------|-------|----------------|\n${pending}\n"
else
  out="${out}None — every Brain is current with its listed materials (per README Status).\n\n"
fi
out="${out}## How readiness is detected (and its honest limits)\n"
out="${out}- **Local materials:** non-README files under \`entities/<type>/<id>/materials/\`.\n"
out="${out}- **Vault materials:** the node id appears in \`registry/vault-manifest.md\`.\n"
out="${out}- **Freshness:** read from the materials \`README.md\` **Status column** (✅/ingested),\n"
out="${out}  NOT file mtimes — this repo is cloned fresh each session, so mtimes are unreliable.\n"
out="${out}- **Not yet covered (→ BACKLOG.md):** live Drive scan via the Drive MCP, content-hash\n"
out="${out}  staleness, and signal-strength scoring of what's waiting.\n"

if [ "$WRITE" = "1" ]; then
  printf "%b" "$out" > registry/brain-queue.md
  echo "(written to registry/brain-queue.md)"
elif [ "$GAPS_ONLY" = "0" ]; then
  printf "%b" "$out"
fi
exit 0
